function roofFinishingStages(selections: ConstructionTechnologySelections): ConstructionTechnologyKey[] {
  const stages: ConstructionTechnologyKey[] = [
    "roofSlopePlate",
    "roofDecking",
    "roofUnderlayment",
    "roofCovering",
  ];
  if (selections.roofCovering === "metal-roof-tile") stages.push("roofMetalTileProfile");
  if (selections.roofCovering === "standing-seam-sheet" || selections.roofCovering === "flat-sheet-metal") {
    stages.push("roofStandingSeamSystem");
  }
  if (selections.roofCovering === "trapezoidal-sheet") stages.push("roofTrapezoidalProfile");
  stages.push("roofChimneySystem");
  if (selections.roofChimneySystem && !["no-chimney", "chimneys-not-in-scope"].includes(selections.roofChimneySystem)) {
    stages.push("roofChimneyFlashing", "roofChimneyFlashingMaterial");
  }
  stages.push("roofGutterSystem", "roofDownspoutSystem");
  return stages;
}

export function getConstructionTechnologyStages(
  workType: ConstructionWorkType,
  selections: ConstructionTechnologySelections,
): readonly ConstructionTechnologyKey[] {
  if (workType === "other") {
    const category = selections.otherWorkTechnology;
    const categories = Array.isArray(category) ? category : category ? [category] : [];
    const stages = new Set<ConstructionTechnologyKey>(["otherWorkTechnology"]);
    const add = (...keys: ConstructionTechnologyKey[]) => keys.forEach((key) => stages.add(key));
    if (categories.includes("foundation-construction")) {
      add(
        "otherWorkPreparation",
        "otherFoundationScope",
        "otherFoundationType",
        "otherFoundationReinforcement",
        "otherFoundationFormwork",
        "otherFoundationConcrete",
      );
    }
    if (categories.includes("reinforced-concrete-work")) {
      add("otherWorkPreparation", "otherConcreteWork", "otherConcreteReinforcement", "otherConcreteFormwork", "otherConcretePlacement");
    }
    if (categories.includes("masonry-work")) {
      add("otherWorkPreparation", "otherMasonryStructure", "otherMasonryMortar", "otherMasonryDetails");
    }
    if (categories.includes("roof-structure")) {
      add("otherWorkPreparation", "otherRoofStructure", "otherRoofDecking");
    }
    if (categories.includes("roof-covering")) {
      add(
        "otherWorkPreparation",
        "otherRoofDecking",
        "otherRoofCovering",
        "otherRoofUnderlayment",
        "otherRoofInsulation",
        "otherRoofDrainage",
      );
    }
    if (categories.includes("fencing")) {
      add("otherWorkPreparation", "otherFenceFoundation", "otherFenceStructure", "otherFenceFinish", "otherFenceAccess");
    }
    if (categories.includes("driveway-paving")) {
      add("otherWorkPreparation", "otherDrivewayBase", "otherDrivewaySurface", "otherDrivewayEdging", "otherDrivewayDrainage");
    }
    const drivewaySurfaces = selections.otherDrivewaySurface;
    if (
      (Array.isArray(drivewaySurfaces) && drivewaySurfaces.includes("paving-resin-gravel"))
      || selections.otherTerraceFinish.includes("terrace-resin-gravel")
    ) {
      add("otherResinGravelSystem");
    }
    if (categories.includes("terrace-construction")) {
      add("otherWorkPreparation", "otherTerraceStructure", "otherTerraceFinish", "otherDrivewayDrainage");
      if (selections.otherTerraceFinish.includes("terrace-resin-gravel")) add("otherResinGravelSystem");
    }
    if (categories.includes("site-drainage")) {
      add("otherWorkPreparation", "otherDrainageTechnology", "otherDrainageOutfall");
    }
    if (categories.includes("external-utility-connections")) {
      add("otherWorkPreparation", "otherExternalConnections");
    }
    if (categories.includes("retaining-wall")) {
      add("otherWorkPreparation", "otherRetainingStructure", "otherRetainingDrainage");
    }
    if (categories.includes("facade-work")) {
      add(
        "otherFacadePreparation",
        "otherFacadeInsulation",
        "otherFacadeFixing",
        "otherFacadeReinforcement",
        "otherFacadeFinish",
      );
      const facadeFinishes = Array.isArray(selections.otherFacadeFinish)
        ? selections.otherFacadeFinish
        : selections.otherFacadeFinish
          ? [selections.otherFacadeFinish]
          : [];
      if (facadeFinishes.some((finish) => ["facade-thin-coat-render", "facade-paint"].includes(finish))) {
        add("otherFacadeCoating", "otherFacadeColor");
      }
    }
    if (categories.includes("windows-doors")) {
      add("otherWorkPreparation", "otherWindowDoorWork");
    }
    if (categories.includes("electrical-installation")) {
      add("otherWorkPreparation", "otherElectricalWork");
    }
    if (categories.includes("water-sewer-installation")) {
      add("otherWorkPreparation", "otherWaterSewerWork");
    }
    if (categories.includes("heating-installation")) {
      add("otherWorkPreparation", "otherHeatingWork");
    }
    if (categories.includes("ventilation-installation")) {
      add("otherWorkPreparation", "otherVentilationWork");
    }
    if (categories.includes("chimney-work")) {
      add("otherWorkPreparation", "otherChimneyWork");
    }
    if (categories.includes("interior-plaster")) {
      add("otherWorkPreparation", "otherInteriorWallWork");
    }
    if (categories.includes("drywall-ceilings")) {
      add("otherWorkPreparation", "otherCeilingWork");
    }
    if (categories.includes("floors-screeds")) {
      add("otherWorkPreparation", "otherFloorWork");
    }
    if (categories.includes("interior-finishing")) {
      add("otherWorkPreparation", "otherInteriorWallWork", "otherCeilingWork", "otherFloorWork", "otherWindowDoorWork");
    }
    if (categories.includes("well-septic-system")) {
      add("otherWorkPreparation", "otherWellSewageWork");
    }
    if (categories.includes("photovoltaic-work")) {
      add("otherWorkPreparation", "otherPhotovoltaicWork");
    }
    if (categories.includes("garage-carport")) {
      add("otherWorkPreparation", "otherFoundationScope", "otherGarageStructure", "otherGarageElements");
    }
    if (categories.includes("garden-landscaping")) {
      add("otherWorkPreparation", "otherGardenWork");
    }
    if (categories.includes("demolition-work")) {
      add("otherWorkPreparation", "otherDemolitionScope");
    }
    if (categories.includes("other-specialist-work")) {
      add("otherWorkPreparation", "otherPrimaryTechnology", "otherFinishTechnology");
    }
    return [...stages];
  }
  if (workType === "renovation") {
    const stages: ConstructionTechnologyKey[] = [
      "renovationScope",
      "renovationDemolition",
      "renovationFloor",
      "renovationWall",
      "renovationCeiling",
    ];
    const scope = selections.renovationScope;
    if (scope === "full-renovation" || scope === "thermal-modernization" || scope === "other-renovation-scope") {
      stages.push("renovationWindows", ...residentialInstallations);
    }
    if (scope === "room-renovation" || scope === "full-renovation" || scope === "other-renovation-scope") {
      stages.push("renovationKitchenFitout", "renovationBathroomFitout");
    }
    if (scope === "thermal-modernization" || scope === "other-renovation-scope") {
      stages.push(
        "foundationWaterproofing",
        "foundationDimpleMembrane",
        "foundationInsulation",
        "wallInsulation",
        "roofStructure",
      );
      if (selections.roofStructure && selections.roofStructure !== "no-roof-work") {
        stages.push(...roofFinishingStages(selections), "roofInsulation");
      }
    }
    return stages;
  }

  const stages: ConstructionTechnologyKey[] = [...residentialCoreStages];
  if (selections.foundationWalls === "monolithic-foundation-wall") stages.splice(3, 0, "foundationFormwork");
  const completion = selections.completionStandard;
  if (
    completion !== "shell-open"
    && completion !== null
    && selections.exteriorWallSystem !== "single-layer-wall"
  ) {
    stages.splice(stages.indexOf("exteriorWallSystem") + 1, 0, "wallInsulation");
  }
  if (["monolithic", "filigree", "rib-and-block"].includes(selections.floorStructure ?? "")) {
    stages.splice(stages.indexOf("floorStructure") + 1, 0, "floorFormwork");
  }
  if (selections.roofStructure && selections.roofStructure !== "no-roof-work") {
    const roofStages = roofFinishingStages(selections);
    if (completion === "developer" || completion === "turnkey" || completion === "other-completion-standard") {
      roofStages.push("roofInsulation");
    }
    stages.splice(stages.indexOf("roofStructure") + 1, 0, ...roofStages);
  }

  if (completion === "shell-closed" || completion === "developer" || completion === "turnkey" || completion === "other-completion-standard") {
    stages.push("windowsSystem");
    if (selections.windowsSystem !== "windows-not-included") stages.push("windowInstallation");
    stages.push("exteriorDoor");
  }
  if (completion === "developer" || completion === "turnkey" || completion === "other-completion-standard") {
    stages.push(...residentialInstallations.filter((key) => !stages.includes(key)), "exteriorFacadeFinish");
  }
  if (completion === "turnkey" || completion === "other-completion-standard") {
    stages.push(...residentialFinishes);
  }
  return stages;
}

