function optionSelection(stage: TechnologyStage) {
  return z.string().nullable().refine(
    (value) => value === null || stage.options.some((option) => option.value === value),
    "Wybierz jedną z dostępnych technologii.",
  );
}
function multipleOptionSelection(stage: TechnologyStage) {
  return z.array(z.string()).max(stage.options.length).refine(
    (values) => new Set(values).size === values.length
      && values.every((value) => stage.options.some((option) => option.value === value))
      && (values.length < 2 || !values.some((value) =>
        value === "project" || /(?:^|-)(?:no-work|no-stairs|not-in-scope|not-included)(?:-|$)/.test(value))),
    `Wybierz dostępne, niepowtarzające się pozycje: ${stage.label}.`,
  );
}

